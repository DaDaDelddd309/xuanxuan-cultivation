const state = { seen: {} };

export const Codex = {
  init() {
    try {
      const r = localStorage.getItem(K);
      if (r) { const d = JSON.parse(r) || {}; state.seen = d.seen || {}; }
    } catch {}
    // 击杀即解锁。这一步之前从来没接过 —— 图鉴不记录「你见过没有」，
    // 所以它只是两张全亮的画册。
    if (!this._hooked) {
      this._hooked = true;
      // Boss 走的也是 enemy-death(敌人对象自带 type 字段),没有单独的 boss 事件。
      // 别再加一个不存在的事件名 —— 那类"看起来合理"的钩子只会静默失效。
      Bus.on('enemy-death', e => { if (e && e.type) this.mark(e.type); });
    }
    return state;
  },

  mark(id) {
    if (!CODEX[id]) return;
    state.seen[id] = (state.seen[id] || 0) + 1;
    this.save();
  },

  count(id) { return state.seen[id] || 0; },
  has(id) { return (state.seen[id] || 0) > 0; },
  seenCount() { return Object.keys(CODEX).filter(k => this.has(k)).length; },
  total() { return Object.keys(CODEX).length; },

  reset() { state.seen = {}; this.save(); },
  save() { try { localStorage.setItem(K, JSON.stringify(state)); } catch {} },
};